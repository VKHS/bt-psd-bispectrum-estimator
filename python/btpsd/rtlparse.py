"""Small structural parser for the Verilog sources in ``rtl/``.

The figure scripts draw the module hierarchy and the control state machines from what this parser reads out of the
sources, and ``python/tests/test_rtl_structure.py`` checks the drawings' specifications against it, so a diagram cannot
drift away from the RTL unnoticed.  It is not a Verilog front end: it understands exactly the coding style of this
repository (one module per file, ``localparam`` state lists, a single ``case (st)`` per state machine, ``generate``
loops written as ``for (v = a; v < b; ...) begin : name``).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

__all__ = ["RTL_DIR", "Instance", "Module", "Port", "parse_all", "parse_module", "fsm_edges", "state_values", "reg_widths",
           "define_values", "default_parameters", "ports"]

RTL_DIR = Path(__file__).resolve().parents[2] / "rtl"

_PAREN2 = r"(?:[^()]|\((?:[^()]|\([^()]*\))*\))*"  # text with parentheses nested up to two levels


@dataclass
class Instance:
    module: str
    name: str
    count: int
    params: dict[str, str] = field(default_factory=dict)


@dataclass
class Module:
    name: str
    path: Path
    lines: int
    instances: list[Instance]
    states: dict[str, int]  # state name -> encoding of the ``st`` machine ({} if the module has none)
    generated: bool


def _strip_comments(src: str) -> str:
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


def _params(text: str | None) -> dict[str, str]:
    if not text:
        return {}
    body = text.strip()[1:].strip()[1:-1]  # drop '#' and the outer parentheses
    return {m.group(1): m.group(2).strip() for m in re.finditer(r"\.(\w+)\s*\(((?:[^()]|\([^()]*\))*)\)", body)}


def _blocks(src: str):
    """Yield ``(start, end, count)`` for every ``for (v = a; v < b; ...) begin : name`` generate block."""
    for m in re.finditer(r"for\s*\(\s*(\w+)\s*=\s*(\d+)\s*;\s*\1\s*<\s*(\d+)\s*;[^)]*\)\s*begin\s*:\s*(\w+)", src):
        depth, pos = 1, m.end()
        for t in re.finditer(r"\bbegin\b|\bend\b", src[pos:]):
            depth += 1 if t.group(0) == "begin" else -1
            if depth == 0:
                yield m.end(), pos + t.start(), int(m.group(3)) - int(m.group(2))
                break


def state_values(src: str) -> dict[str, int]:
    """Names and encodings of the state ``localparam`` lists (``NAME = N'dV``)."""
    states: dict[str, int] = {}
    for m in re.finditer(r"localparam\s*(?:\[[^\]]*\])?\s*([^;]+);", src):
        body = m.group(1)
        found = re.findall(r"(\w+)\s*=\s*\d+'d(\d+)", body)
        if found and len(found) == len([x for x in body.split(",") if x.strip()]):
            states.update({n: int(v) for n, v in found})
    return states


def parse_module(path: Path, known: set[str]) -> Module:
    raw = Path(path).read_text()
    src = _strip_comments(raw)
    name = re.search(r"\bmodule\s+(\w+)", src).group(1)
    blocks = list(_blocks(src))
    insts: list[Instance] = []
    pat = re.compile(r"\b(" + "|".join(sorted(known - {name})) + r")\s*(#\s*\(" + _PAREN2 + r"\))?\s*(\w+)\s*\(")
    for m in pat.finditer(src):
        count = 1
        for s, e, c in blocks:
            if s <= m.start() < e:
                count *= c
        insts.append(Instance(m.group(1), m.group(3), count, _params(m.group(2))))
    return Module(name, Path(path), raw.count("\n"), insts, state_values(src),
                  generated="Generated by" in raw[:200] or "generated by" in raw[:200])


def parse_all(rtl_dir: Path = RTL_DIR) -> dict[str, Module]:
    paths = sorted(Path(rtl_dir).glob("*.v"))
    known = {re.search(r"\bmodule\s+(\w+)", _strip_comments(p.read_text())).group(1) for p in paths}
    return {m.name: m for m in (parse_module(p, known) for p in paths)}


def fsm_edges(path: Path, var: str = "st") -> dict[tuple[str, str], int]:
    """Transitions ``(from, to)`` of the ``case (st)`` machine of ``path`` (self loops are not listed).

    The value is the number of ``st <= to`` assignments found in the arm of ``from``.  A ``default`` arm belongs to the
    one state that has no arm of its own.
    """
    src = _strip_comments(Path(path).read_text())
    states = state_values(src)
    start = re.search(r"case\s*\(\s*" + var + r"\s*\)", src)
    if not start:
        return {}
    depth, pos, end = 1, start.end(), None
    for t in re.finditer(r"\bcase[xz]?\b|\bendcase\b", src[pos:]):
        depth += 1 if t.group(0).startswith("case") else -1
        if depth == 0:
            end = pos + t.start()
            break
    body = src[start.end():end]
    names = "|".join(sorted(states, key=len, reverse=True))
    arms = [(m.start(), m.group(1)) for m in re.finditer(r"(?m)^\s*(" + names + r"|default)\s*:", body)]
    edges: dict[tuple[str, str], int] = {}
    listed = {a for _, a in arms if a != "default"}
    for i, (p0, label) in enumerate(arms):
        p1 = arms[i + 1][0] if i + 1 < len(arms) else len(body)
        text = body[p0:p1]
        src_state = label
        if label == "default":
            missing = set(states) - listed
            if len(missing) != 1:
                raise ValueError(f"{path}: default arm of a machine with {len(missing)} unlisted states")
            src_state = missing.pop()
        for m in re.finditer(r"\b" + var + r"\s*<=\s*(?:[^;?]+\?\s*(\w+)\s*:\s*(\w+)|(\w+))\s*;", text):
            for tgt in m.groups():
                if tgt and tgt in states and tgt != src_state:
                    edges[(src_state, tgt)] = edges.get((src_state, tgt), 0) + 1
    return edges


def reg_widths(path: Path, env: dict[str, int]) -> dict[str, int]:
    """Width in bits of every ``reg`` declared in ``path`` (a range ``[hi:0]`` is evaluated with the parameters ``env``)."""
    src = _strip_comments(Path(path).read_text())
    widths: dict[str, int] = {}
    for m in re.finditer(r"\breg\b\s*(?:signed\s*)?(?:\[([^\]:]+):0\]\s*)?([^;\[]+);", src):
        width = 1 if m.group(1) is None else int(eval(m.group(1), {"__builtins__": {}}, dict(env))) + 1  # noqa: S307
        for name in m.group(2).split(","):
            name = name.strip()
            if re.fullmatch(r"\w+", name):
                widths[name] = width
    return widths


def define_values(path: Path) -> dict[str, int]:
    """Integer ```define NAME value`` lines of a Verilog header."""
    out: dict[str, int] = {}
    for m in re.finditer(r"(?m)^`define\s+(\w+)\s+(-?\d+)\s*$", Path(path).read_text()):
        out[m.group(1)] = int(m.group(2))
    return out


@dataclass
class Port:
    name: str
    direction: str  # "input" | "output"
    width: int
    signed: bool
    is_reg: bool


def _header(src: str) -> tuple[str, str]:
    """Text of the ``#( ... )`` parameter list and of the port list of the first module declaration (comments stripped)."""
    m = re.search(r"\bmodule\s+\w+\s*(?:#\s*\((" + _PAREN2 + r")\))?\s*\((" + _PAREN2 + r")\)\s*;", src)
    if m is None:
        raise ValueError("no module header found")
    return m.group(1) or "", m.group(2)


_SIZED = re.compile(r"(\d+)\s*'\s*([sS]?)\s*([bBoOdDhH])\s*([0-9a-fA-F_]+)")
_BASE = {"b": 2, "o": 8, "d": 10, "h": 16}


def _literal(m: re.Match) -> str:
    """Python text of a sized Verilog literal such as ``32'hA5A51F3D`` (an unsigned value, or the two's complement of a signed one)."""
    width, signed, base, digits = int(m.group(1)), bool(m.group(2)), m.group(3).lower(), m.group(4).replace("_", "")
    v = int(digits, _BASE[base]) & ((1 << width) - 1)
    if signed and v >> (width - 1):
        v -= 1 << width
    return str(v)


def _eval(expr: str, env: dict[str, int]) -> int:
    expr = _SIZED.sub(_literal, expr)
    return int(eval(expr, {"__builtins__": {}}, dict(env)))  # noqa: S307 - expressions come from our own sources


def default_parameters(path: Path, env: dict[str, int] | None = None) -> dict[str, int]:
    """Values of the ``parameter`` list of a module header, evaluated in order; ``env`` overrides defaults by name.

    A default that uses a macro (a backtick name) is left out unless ``env`` supplies the parameter.
    """
    params_text, _ = _header(_strip_comments(Path(path).read_text()))
    env = dict(env or {})
    values: dict[str, int] = {}
    for chunk in re.split(r"\bparameter\b", params_text)[1:]:
        m = re.match(r"\s*(?:signed\s+)?(?:\[[^\]]*\]\s*)?(\w+)\s*=\s*(.+?)\s*,?\s*$", chunk, re.S)
        if m is None:
            continue
        name, expr = m.group(1), m.group(2)
        if name in env:
            values[name] = env[name]
        elif "`" not in expr:
            values[name] = _eval(expr, {**values, **env})
    return values


def _split_top(text: str) -> list[str]:
    """Split ``text`` at the commas that are not inside parentheses or brackets."""
    parts, depth, cur = [], 0, []
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur))
    return [p.strip() for p in parts if p.strip()]


def ports(path: Path, env: dict[str, int] | None = None) -> list[Port]:
    """Ports of the first module of ``path`` in declaration order, widths evaluated with the module parameters (``env`` overrides)."""
    values = default_parameters(path, env)
    values.update(env or {})
    _, text = _header(_strip_comments(Path(path).read_text()))
    out: list[Port] = []
    last = None
    for piece in _split_top(text):
        m = re.fullmatch(r"(?:(input|output)\s+(reg\s+|wire\s+)?(signed\s+)?(?:\[([^\]]+)\]\s*)?)?(\w+)", piece, re.S)
        if m is None:
            raise ValueError(f"cannot parse port declaration {piece!r}")
        direction, kind, signed, rng, name = m.groups()
        if direction is None:
            if last is None:
                raise ValueError(f"port {name!r} has no direction")
            direction, is_reg, is_signed, width = last
        else:
            width = 1
            if rng is not None:
                hi, lo = rng.split(":")
                width = _eval(hi, values) - _eval(lo, values) + 1
            is_reg, is_signed = bool(kind and kind.strip() == "reg"), bool(signed)
            last = (direction, is_reg, is_signed, width)
        out.append(Port(name, direction, width, is_signed, is_reg))
    return out
