# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
def pack(fields) -> list[int]:
    """Concatenate ``(array, width)`` fields (MSB first) into Python ints, one per row.

    Signed arrays are wrapped to two's complement of their width.
    """
    arrs = [np.asarray(a, dtype=np.int64) for a, _ in fields]
    n = arrs[0].shape[0]
    out = []
    for i in range(n):
        v = 0
        for a, (_, w) in zip(arrs, fields):
            v = (v << w) | (int(a[i]) & ((1 << w) - 1))
        out.append(v)
    return out


def bus(a, wl: int) -> np.ndarray:
    """``(n, k)`` signed words -> ``(n,)`` bus values with element ``m`` at bit offset ``m * wl``."""
    a = np.asarray(a, dtype=np.int64)
    n, k = a.shape
    out = np.zeros(n, dtype=object)
    for m in range(k):
        out = out + (a[:, m] & ((1 << wl) - 1)).astype(object) * (1 << (m * wl))
    return out


def write_mem(path: Path, values, width: int) -> None:
    """Write ints as zero-padded lower-case hex lines."""
    digits = (width + 3) // 4
    mask = (1 << width) - 1
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        for v in values:
            f.write(f"{int(v) & mask:0{digits}x}\n")


def _corners(wl: int):
    hi, lo = (1 << (wl - 1)) - 1, -(1 << (wl - 1))
    return hi, lo


# ---------------------------------------------------------------------------
# constant rotator
# ---------------------------------------------------------------------------
def cru_vectors(wl: int = 16, tol: float = 0.01, n_random: int = 2048, seed: int = 1) -> dict:
    """All 1024 twiddle indices with corner and random data, plus extra random rows.

    Input word ``{xr[wl], xi[wl], q[10]}``, output word ``{yr[wl], yi[wl]}``.
    """
    rom = default_rom(tol)
    rng = np.random.default_rng(seed)
    hi, lo = _corners(wl)
    corner = np.array([(hi, hi), (lo, lo), (hi, lo), (lo, hi), (0, 0), (1, 0), (0, 1)], dtype=np.int64)
    q_c = np.repeat(np.arange(1024), len(corner))
    xr_c = np.tile(corner[:, 0], 1024)
    xi_c = np.tile(corner[:, 1], 1024)
    q_r = rng.integers(0, 1024, n_random)
    xr_r = rng.integers(lo, hi + 1, n_random)
    xi_r = rng.integers(lo, hi + 1, n_random)
    q = np.concatenate([q_c, q_r])
    xr = np.concatenate([xr_c, xr_r])
    xi = np.concatenate([xi_c, xi_r])
    yr, yi = rotate_fixed(xr, xi, q, rom, wl, "round")
    return {
        "wl": wl,
        "in": pack([(xr, wl), (xi, wl), (q, 10)]),
        "in_width": 2 * wl + 10,
        "out": pack([(yr, wl), (yi, wl)]),
        "out_width": 2 * wl,
        "n": len(q),
    }


# ---------------------------------------------------------------------------
# radix-8 butterfly (8-point DFT + output twiddles)
# ---------------------------------------------------------------------------
def bfly_vectors(wl: int = 16, tol: float = 0.01, n: int = 2048, seed: int = 2) -> dict:
    """Input ``{xr_bus, xi_bus, tq_bus}`` (``8wl + 8wl + 70`` bits), output ``{yr_bus, yi_bus}``.

    ``x`` slot ``m`` sits at bit offset ``m*wl``; ``tq`` slot ``k = 1..7`` at offset ``(k-1)*10``.
    """
    rom = default_rom(tol)
    rng = np.random.default_rng(seed)
    hi, lo = _corners(wl)
    xr = rng.integers(lo, hi + 1, (n, 8))
    xi = rng.integers(lo, hi + 1, (n, 8))
    xr[: n // 8] //= 16  # small signals: exercise rounding rather than only large codes
    xi[: n // 8] //= 16
    # corner rows
    xr[0], xi[0] = hi, hi
    xr[1], xi[1] = lo, lo
    xr[2], xi[2] = np.tile([hi, lo], 4), np.tile([lo, hi], 4)
    xr[3], xi[3] = 0, 0
    tq = rng.integers(0, 1024, (n, 8))
    tq[:, 0] = 0
    tq[: 64, 1:] = np.arange(64)[:, None] * 2 * np.arange(1, 8)[None, :] % 1024  # pass-0 twiddles of a real FFT
    yr, yi = dft8_fixed(xr, xi, rom, wl, "round")
    yr, yi = rotate_fixed(yr, yi, tq, rom, wl, "round")
    tq_bus = np.zeros(n, dtype=object)
    for k in range(1, 8):
        tq_bus = tq_bus + tq[:, k].astype(object) * (1 << ((k - 1) * 10))
    xr_b, xi_b = bus(xr, wl), bus(xi, wl)
    yr_b, yi_b = bus(yr, wl), bus(yi, wl)
    ins = [(int(a) << (8 * wl + 70)) | (int(b) << 70) | int(c) for a, b, c in zip(xr_b, xi_b, tq_bus)]
    outs = [(int(a) << (8 * wl)) | int(b) for a, b in zip(yr_b, yi_b)]
    return {"wl": wl, "in": ins, "in_width": 16 * wl + 70, "out": outs, "out_width": 16 * wl, "n": n}


# ---------------------------------------------------------------------------
# 512-point FFT
# ---------------------------------------------------------------------------
def fft_vectors(wl: int = 16, tol: float = 0.01, seed: int = 3) -> dict:
    """Four chunks: complex random, real tone + noise, constant maximum, alternating extremes."""
    rom = default_rom(tol)
    rng = np.random.default_rng(seed)
    hi, lo = _corners(wl)
    n = np.arange(512)
    chunks_r = [
        rng.integers(lo, hi + 1, 512),
        np.round(0.6 * hi * np.cos(2 * np.pi * 37.3 * n / 512) + 0.05 * hi * rng.standard_normal(512)).astype(np.int64),
        np.full(512, hi),
        np.where(n % 2 == 0, hi, lo),
    ]
    chunks_i = [rng.integers(lo, hi + 1, 512), np.zeros(512, dtype=np.int64), np.full(512, lo), np.zeros(512, dtype=np.int64)]
    re = np.array(chunks_r, dtype=np.int64)
    im = np.array(chunks_i, dtype=np.int64)
    Yr, Yi = r8fft_fixed(re, im, rom, wl, "round")
    sched = schedule_cycles(LAT)  # first issue to the cycle in which the last written word can be read
    return {"wl": wl, "in_re": re.ravel(), "in_im": im.ravel(), "out_re": Yr.ravel(), "out_im": Yi.ravel(), "nchunks": 4,
            "total_cycles": sched["total_cycles"], "stall_cycles": int(sum(sched["stalls_per_pass"]))}


# ---------------------------------------------------------------------------
# sum-of-odds squarer
# ---------------------------------------------------------------------------
def sq_vectors(wl: int = 16, n: int = 1024, seed: int = 4) -> dict:
    """Small-magnitude pairs (the serial squarer needs ``max(|re|, |im|)`` cycles)."""
    rng = np.random.default_rng(seed)
    re = np.round(rng.laplace(0, 20, n)).astype(np.int64)
    im = np.round(rng.laplace(0, 20, n)).astype(np.int64)
    re[:8] = [0, 1, -1, 0, 5, -5, 127, -128]
    im[:8] = [0, 0, 0, -1, 5, -5, -127, 128]
    re = np.clip(re, -400, 400)
    im = np.clip(im, -400, 400)
    p = re * re + im * im
    return {"wl": wl, "in": pack([(re, wl), (im, wl)]), "in_width": 2 * wl, "out": [int(v) for v in p], "out_width": 2 * wl, "n": n,
            "cycles": np.maximum(np.abs(re), np.abs(im))}


# ---------------------------------------------------------------------------
# PSD (whole estimator)
# ---------------------------------------------------------------------------
def clipped_tone(n: int, seed: int, bin_1024: float = 100.5, gain: float = 1.3, noise: float = 0.3) -> np.ndarray:
    """Hard-clipped full-scale tone half-way between two 512-point bins plus noise (phase continuous in ``n``).

    The tone sits on an odd bin of the 1024-bin grid, so the fractional-delay merge and the window see their largest
    inputs; the clipping adds broadband energy and puts many samples on the extreme codes.
    """
    k = np.arange(n)
    w = np.random.default_rng(seed).standard_normal(n)
    return np.clip(gain * np.sin(2 * np.pi * bin_1024 * k / 1024) + noise * w, -1.0, 1.0)


def psd_vectors(wl: int = 12, window: str = "hann", nchunks: int = 4, seed: int = 5, peak: float = 0.5,
                stress_from: int = 2, rounding: str = "round") -> dict:
    """Input: ``nchunks * 512`` real sample codes; expected: ``P_int`` (1024 words) of :func:`psd_fixed`.

    Chunks before ``stress_from`` are pink noise at ``peak``; from there on the input is a hard-clipped full-scale tone
    (:func:`clipped_tone`), so that the saturating paths of the engine are part of the comparison.
    """
    cfg = HwConfig(wl=wl, window=window, rounding=rounding)
    x = sg.pink(nchunks * 512, seed, peak=peak)
    if stress_from < nchunks:
        x[stress_from * 512:] = clipped_tone(nchunks * 512, seed + 100)[stress_from * 512:]
    codes, _ = to_fixed(x, wl, cfg.rounding)
    res = psd_fixed(codes, cfg, quantize=False)
    return {"cfg": cfg, "x": codes, "P": res.P_int, "S": res.S, "avg_shift": res.avg_shift, "acc": res.acc,
            "squarer_cycles": res.squarer_cycles, "nchunks": nchunks, "fd": cfg.fd_int(), "win": cfg.win_int()}


# ---------------------------------------------------------------------------
# bispectrum
# ---------------------------------------------------------------------------
def bispec_vectors(wl: int = 12, window: str = "hann", nsamples: int = 512 * 3, max_bin: int = 32, seed: int = 6,
                   stress_from: int = 768, rounding: str = "round") -> dict:
    """Input sample codes (hop 256, 512-sample frames); expected ``B_re, B_im`` of :func:`bispectrum_fixed`.

    The first ``stress_from`` samples are the coupled test signal at 0.6 of its peak; the rest is the same signal
    amplified 2.5 times and hard-clipped to full scale, so that the saturating paths of the engine are exercised.
    """
    cfg = BispecConfig(wl=wl, window=window, max_bin=max_bin, rounding=rounding)
    x, _ = sg.qpc(nsamples, coupled=True, seed=seed)
    x = np.asarray(x, dtype=float)
    y = 0.6 * x
    y[stress_from:] = np.clip(2.5 * x[stress_from:], -1.0, 1.0)
    codes, _ = to_fixed(y, wl, cfg.rounding)
    xs = codes.astype(float) / float(1 << (wl - 1))
    re, im, S, shift = bispectrum_fixed(xs, cfg)
    return {"cfg": cfg, "x": codes, "B_re": re, "B_im": im, "S": S, "avg_shift": shift}


