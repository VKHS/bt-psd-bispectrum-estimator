"""Generate the Black Box files of the Model Composer flow from the Verilog sources.

    PYTHONPATH=python python3 python/scripts/gen_mc.py [--wl 12] [--nchunks 5] [--round 1] [--sq-serial 1] [--out-dir modelcomposer]

Writes, below ``--out-dir``:

``hdl/bt_psd_mc_bundle.v``
    every Verilog module the block needs in ONE file without compiler directives other than ``timescale``: the RTL files
    of ``bt_psd_top`` and the wrapper ``bt_psd_mc`` with the header macros (``btpsd_consts.vh``, ``btpsd_params.vh``)
    expanded and the ``include`` lines removed.  The Black Box import is given this file, so it does not depend on how a
    tool resolves ``include``.  The defaults of the wrapper's parameters are set to the requested configuration.
``matlab/bt_psd_mc_config.m``
    the Black Box configuration function: ports and port types read from the wrapper's port list (``btpsd.rtlparse.ports``),
    the single clock/clock-enable pair and the file to compile.
``matlab/bt_mc_params.m``
    the parameters of the build (word length, chunks, segments, averaging shift, widths, power scale) as a MATLAB struct.
``hdl/sig_rom.v``
    the 1024-entry sine table of the in-fabric test-signal generator ``sig_gen.v`` (``btpsd.siggen.rom_table``).

Nothing here runs MATLAB or Vivado.  The generated Verilog is simulated by ``make -C sim mc mcb`` (Icarus Verilog); the
generated MATLAB is plain text that has not been executed in the environment this repository was developed in.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from _common import ROOT

from btpsd import siggen
from btpsd.estimator import hw_power_scale
from btpsd.rtlparse import RTL_DIR, define_values, ports

WRAPPER = ROOT / "modelcomposer" / "hdl" / "bt_psd_mc.v"
BUNDLE_ORDER = ["delay_line.v", "ram_1r1w.v", "cru_rom.v", "cru_rotate.v", "r8_butterfly.v", "fft512_mem.v", "mag_sq_odd.v",
                "psd_engine.v", "bt_psd_top.v"]
HEADERS = ["btpsd_params.vh", "btpsd_consts.vh"]
DEFAULTS = dict(wl=12, nchunks=5, rounding=1, sq_serial=1)
ENTITY = "bt_psd_mc"


# ---------------------------------------------------------------------------------------------------------------
# bundle
# ---------------------------------------------------------------------------------------------------------------
def header_macros() -> dict[str, int]:
    out: dict[str, int] = {}
    for h in HEADERS:
        out.update(define_values(RTL_DIR / h))
    return out


def flatten(text: str, macros: dict[str, int], name: str) -> str:
    """Remove the ``include`` lines of the two headers and replace every macro use by its value (negative values in parentheses)."""
    lines = []
    for ln in text.splitlines():
        m = re.match(r'\s*`include\s+"([^"]+)"\s*$', ln)
        if m:
            if m.group(1) not in HEADERS:
                raise ValueError(f"{name}: include of {m.group(1)!r}, which the bundle does not know")
            continue
        lines.append(ln)
    out = "\n".join(lines) + "\n"

    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key == "timescale":
            return m.group(0)
        if key not in macros:
            raise ValueError(f"{name}: unknown macro `{key}")
        v = macros[key]
        return f"({v})" if v < 0 else str(v)

    return re.sub(r"`(\w+)", sub, out)


def set_defaults(wrapper: str, wl: int, nchunks: int, rounding: int, sq_serial: int) -> str:
    """Set the defaults of the wrapper's parameters WL, ROUND, SQ_SERIAL and NCHUNKS (each must occur exactly once)."""
    out = wrapper
    for name, val in (("WL", wl), ("ROUND", rounding), ("SQ_SERIAL", sq_serial), ("NCHUNKS", nchunks)):
        out, n = re.subn(rf"(parameter\s+{name}\s*=\s*)\d+", rf"\g<1>{val}", out, count=1)
        if n != 1:
            raise ValueError(f"parameter {name} not found in the wrapper")
    return out


def bundle_text(wl: int = 12, nchunks: int = 5, rounding: int = 1, sq_serial: int = 1) -> str:
    macros = header_macros()
    parts = [
        f"// Generated by python/scripts/gen_mc.py; do not edit.  Include-free bundle of the PSD estimator for the Model Composer Black Box.\n"
        f"// Top level: {ENTITY} (WL = {wl}, NCHUNKS = {nchunks}, ROUND = {rounding}, SQ_SERIAL = {sq_serial}).  Sources: "
        + ", ".join(f"rtl/{f}" for f in BUNDLE_ORDER) + ", modelcomposer/hdl/bt_psd_mc.v.\n"
        "// Header macros of btpsd_consts.vh and btpsd_params.vh are expanded; behaviour is that of the sources (make -C sim mc mcb).\n"
        "`timescale 1ns / 1ps\n"
    ]
    for f in BUNDLE_ORDER:
        body = flatten((RTL_DIR / f).read_text(), macros, f)
        body = re.sub(r"(?m)^`timescale[^\n]*\n", "", body)
        parts.append(f"\n// ===== rtl/{f} =====\n{body}")
    wrap = flatten(WRAPPER.read_text(), macros, "bt_psd_mc.v")
    wrap = re.sub(r"(?m)^`timescale[^\n]*\n", "", wrap)
    parts.append(f"\n// ===== modelcomposer/hdl/bt_psd_mc.v =====\n{set_defaults(wrap, wl, nchunks, rounding, sq_serial)}")
    return "".join(parts)


# ---------------------------------------------------------------------------------------------------------------
# sine table of the test-signal generator
# ---------------------------------------------------------------------------------------------------------------
def sig_rom_text(wl: int = 12) -> str:
    """Verilog of ``sig_rom``: ``dout`` is ``round(TONE_AMP * 2**(wl-1) * sin(2 pi k / 1024))`` one enabled clock after ``addr = k``."""
    rom = siggen.rom_table(wl)
    digits = (wl + 3) // 4
    mask = (1 << wl) - 1
    L = [
        "// Generated by python/scripts/gen_mc.py; do not edit.",
        f"// 1024-entry sine table of sig_gen.v for WL = {wl}: round({siggen.TONE_AMP} * 2^{wl - 1} * sin(2 pi k / 1024)), two's complement.",
        "// For another word length run: python3 python/scripts/gen_mc.py --wl <WL>  (and give sig_gen / bt_psd_selftest the same WL).",
        "`timescale 1ns / 1ps",
        "",
        f"module sig_rom #(parameter WL = {wl}) (",
        "    input              clk,",
        "    input              en,",
        "    input      [9:0]   addr,",
        "    output reg [WL-1:0] dout",
        ");",
        "    reg [WL-1:0] mem [0:1023];",
        "    initial begin",
    ]
    for k, v in enumerate(rom):
        L.append(f"        mem[{k}] = {wl}'h{int(v) & mask:0{digits}x};")
    L += ["    end", "    always @(posedge clk) if (en) dout <= mem[addr];", "endmodule", ""]
    return "\n".join(L)


# ---------------------------------------------------------------------------------------------------------------
# MATLAB
# ---------------------------------------------------------------------------------------------------------------
def build_params(wl: int, nchunks: int, rounding: int, sq_serial: int) -> dict:
    segments = nchunks - 1
    shift = max(0, (segments - 1).bit_length())  # ceil(log2(segments)), as the wrapper computes it
    return dict(wl=wl, round=rounding, sq_serial=sq_serial, nchunks=nchunks, nsamp=nchunks * 512, segments=segments, avg_shift=shift,
                accw=2 * wl + 8, bins=1024, scale=hw_power_scale(wl, segments, shift))


def params_m(p: dict) -> str:
    return f"""function p = bt_mc_params()
% Parameters of the generated Black Box '{ENTITY}' (python/scripts/gen_mc.py; do not edit, regenerate instead).
%   wl         word length of the samples: Fix_<wl>_<wl-1> at the Black Box input (-1 <= x < 1)
%   nchunks    chunks of 512 samples recorded per run;  segments = nchunks - 1 overlapping 1024-sample segments are averaged
%   avg_shift  ceil(log2(segments)): the hardware divides the accumulated power by 2^avg_shift
%   accw       width of rd_data (UFix_<accw>_0), bins = 1024 (two-sided spectrum)
%   scale      P_welch = rd_data * scale  (btpsd.estimator.hw_power_scale): the scale of the floating-point Welch average with the
%              '/L' normalisation of btpsd.reference.welch_twosided(scaling = 'paper')
p.wl = {p['wl']};
p.round = {p['round']};
p.sq_serial = {p['sq_serial']};
p.nchunks = {p['nchunks']};
p.nsamp = {p['nsamp']};
p.segments = {p['segments']};
p.avg_shift = {p['avg_shift']};
p.accw = {p['accw']};
p.bins = {p['bins']};
p.in_type = 'Fix_{p['wl']}_{p['wl'] - 1}';
p.out_type = 'UFix_{p['accw']}_0';
p.scale = {p['scale']!r};
end
"""


def config_m(wl: int, nchunks: int, rounding: int, sq_serial: int) -> str:
    env = dict(WL=wl, NCHUNKS=nchunks, ROUND=rounding, SQ_SERIAL=sq_serial)
    pl = ports(WRAPPER, env)
    clk = [p for p in pl if p.name == "clk"]
    ce = [p for p in pl if p.name == "ce"]
    if len(clk) != 1 or len(ce) != 1:
        raise ValueError("the wrapper needs exactly one clk and one ce port")
    ins = [p for p in pl if p.direction == "input" and p.name not in ("clk", "ce")]
    outs = [p for p in pl if p.direction == "output"]
    L = []
    a = L.append
    a("function bt_psd_mc_config(this_block)")
    a(f"% Black Box configuration of '{ENTITY}' for Model Composer / System Generator.")
    a("% Generated by python/scripts/gen_mc.py from modelcomposer/hdl/bt_psd_mc.v; do not edit, regenerate instead.")
    a(f"% Configuration: WL = {wl}, NCHUNKS = {nchunks}, ROUND = {rounding}, SQ_SERIAL = {sq_serial}.")
    a("% Not executed in the environment this repository was developed in (no MATLAB there): see docs/MODEL_COMPOSER.md.")
    a("")
    a("  this_block.setTopLevelLanguage('Verilog');")
    a(f"  this_block.setEntityName('{ENTITY}');")
    a("")
    a("  % Registered paths (the read data follows rd_addr one clock later): do not tag the block as combinational.")
    for p in ins:
        a(f"  this_block.addSimulinkInport('{p.name}');")
    a("")
    for p in outs:
        a(f"  this_block.addSimulinkOutport('{p.name}');")
    a("")
    for p in outs:
        a(f"  {p.name}_port = this_block.port('{p.name}');")
        a(f"  {p.name}_port.setType('UFix_{p.width}_0');")
        a(f"  {p.name}_port.useHDLVector({'true' if p.width > 1 else 'false'});")
    a("")
    a("  % -----------------------------")
    a("  if (this_block.inputTypesKnown)")
    a(f"    % the widths the HDL was written for (gateways: Fix_{wl}_{wl - 1} for in_data, UFix_10_0 for rd_addr, Boolean for the rest)")
    for p in ins:
        a(f"    if (this_block.port('{p.name}').width ~= {p.width})")
        a(f"      this_block.setError('Input data type for port \"{p.name}\" must have width={p.width}.');")
        a("    end")
        a(f"    this_block.port('{p.name}').useHDLVector({'true' if p.width > 1 else 'false'});")
    a("  end  % if(inputTypesKnown)")
    a("  % -----------------------------")
    a("")
    a("  % -----------------------------")
    a("  if (this_block.inputRatesKnown)")
    a(f"    setup_as_single_rate(this_block,'{clk[0].name}','{ce[0].name}')")
    a("  end  % if(inputRatesKnown)")
    a("  % -----------------------------")
    a("")
    a("  % The bundle holds every module the block needs; it is compiled as one file.")
    a("  here = fileparts(mfilename('fullpath'));")
    a("  this_block.addFile(fullfile(here, '..', 'hdl', 'bt_psd_mc_bundle.v'));")
    a("return;")
    a("")
    a("% ------------------------------------------------------------")
    a("function setup_as_single_rate(block,clkname,cename)")
    a("  inputRates = block.inputRates;")
    a("  uniqueInputRates = unique(inputRates);")
    a("  if (length(uniqueInputRates)==1 && uniqueInputRates(1)==Inf)")
    a("    block.addError('The inputs to this block cannot all be constant.');")
    a("    return;")
    a("  end")
    a("  if (uniqueInputRates(end) == Inf)")
    a("     uniqueInputRates = uniqueInputRates(1:end-1);")
    a("  end")
    a("  if (length(uniqueInputRates) ~= 1)")
    a("    block.addError('The inputs to this block must run at a single rate.');")
    a("    return;")
    a("  end")
    a("  theInputRate = uniqueInputRates(1);")
    a("  for i = 1:block.numSimulinkOutports")
    a("     block.outport(i).setRate(theInputRate);")
    a("  end")
    a("  block.addClkCEPair(clkname,cename,theInputRate);")
    a("return;")
    a("")
    return "\n".join(L)


# ---------------------------------------------------------------------------------------------------------------
def write_all(out_dir: Path, wl: int, nchunks: int, rounding: int, sq_serial: int) -> list[Path]:
    if nchunks < 2:
        raise ValueError("nchunks must be at least 2 (one segment needs two chunks)")
    if wl < 8:
        raise ValueError("wl must be at least 8")
    files = {
        out_dir / "hdl" / "bt_psd_mc_bundle.v": bundle_text(wl, nchunks, rounding, sq_serial),
        out_dir / "matlab" / "bt_psd_mc_config.m": config_m(wl, nchunks, rounding, sq_serial),
        out_dir / "matlab" / "bt_mc_params.m": params_m(build_params(wl, nchunks, rounding, sq_serial)),
        out_dir / "hdl" / "sig_rom.v": sig_rom_text(wl),
    }
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return list(files)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wl", type=int, default=DEFAULTS["wl"], help="sample word length (default %(default)s)")
    ap.add_argument("--nchunks", type=int, default=DEFAULTS["nchunks"], help="512-sample chunks per run, segments = nchunks - 1 (default %(default)s)")
    ap.add_argument("--round", type=int, default=DEFAULTS["rounding"], choices=(0, 1), help="1: rounding to nearest, 0: truncation")
    ap.add_argument("--sq-serial", type=int, default=DEFAULTS["sq_serial"], choices=(0, 1), help="1: serial sum-of-odds squarer")
    ap.add_argument("--out-dir", type=Path, default=ROOT / "modelcomposer")
    a = ap.parse_args()
    for p in write_all(a.out_dir, a.wl, a.nchunks, a.round, a.sq_serial):
        print("wrote", p)


if __name__ == "__main__":
    main()
