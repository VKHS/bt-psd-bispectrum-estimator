"""Generate the constant parts of the RTL from the Python model.

    PYTHONPATH=python python3 python/scripts/gen_rtl.py [--tol 0.01]

Writes ``rtl/cru_rom.v`` (the rotator coefficient ROM, ``r = 0..128``) and
``rtl/btpsd_consts.vh`` (fractional-delay and window tap constants as macros).
Both are derived from the same objects the bit-accurate models use, so the RTL
cannot drift from the model.
"""

from __future__ import annotations

import argparse

import numpy as np

from _common import ROOT

from btpsd.cordic import default_rom
from btpsd.estimator import HwConfig


def cru_rom_v(tol: float) -> str:
    rom = default_rom(tol)
    err = rom.angle_error()
    lines = [
        f"// Generated by python/scripts/gen_rtl.py from btpsd.cordic.default_rom(tol={tol}); do not edit.",
        f"// {rom.n} entries, r = 0..128 in units of pi/512.  For each r the rotator computes",
        "//   y = x * (a -/+ j b) * inv / 2^14      with   inv / 2^14 ~ 1 / |a + j b|",
        f"// maximum angle error {np.abs(err).max():.4f} rad, rms {np.sqrt(np.mean(err ** 2)):.4f} rad, "
        f"gain error <= 2^-10, mean {rom.adders().mean():.2f} adders per rotation (model count).",
        "module cru_rom (",
        "    input  [7:0]  r,",
        "    output reg [7:0]  a,",
        "    output reg [7:0]  b,",
        "    output reg [14:0] inv",
        ");",
        "    always @* begin",
        "        case (r)",
    ]
    for r in range(rom.n):
        lines.append(f"            8'd{r}: begin a = 8'd{int(rom.a[r])}; b = 8'd{int(rom.b[r])}; inv = 15'd{int(rom.inv[r])}; end")
    lines += [
        "            default: begin a = 8'd1; b = 8'd0; inv = 15'd16384; end",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def consts_vh() -> str:
    cfg = HwConfig()
    h = cfg.fd_int()
    out = [
        "// Generated by python/scripts/gen_rtl.py; do not edit.",
        "// Six-tap fractional-delay filter (paper Eq. 6) as integers with FD_FRAC fraction bits; tap i has offset d = -2 + i.",
        f"`define FD_FRAC {cfg.fd_frac}",
    ]
    for i, v in enumerate(h):
        out.append(f"`define FD_H{i} {int(v)}")
    out += [
        "// Frequency-domain window kernels  Xw[k] = sum_d W[d] X[k-d]  with WIN_FRAC fraction bits, d = -2..2.",
        f"`define WIN_FRAC {cfg.win_frac}",
    ]
    for name in ("rect", "hann", "hamming", "blackman"):
        c = HwConfig(window=name).win_int()
        for d in range(-2, 3):
            tag = f"M{-d}" if d < 0 else (f"P{d}" if d > 0 else "0")
            out.append(f"`define WIN_{name.upper()}_{tag} {int(c.get(d, 0))}")
    out.append("")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tol", type=float, default=0.01)
    a = ap.parse_args()
    (ROOT / "rtl").mkdir(exist_ok=True)
    (ROOT / "rtl" / "cru_rom.v").write_text(cru_rom_v(a.tol))
    (ROOT / "rtl" / "btpsd_consts.vh").write_text(consts_vh())
    print("wrote rtl/cru_rom.v and rtl/btpsd_consts.vh")


if __name__ == "__main__":
    main()
