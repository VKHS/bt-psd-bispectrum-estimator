"""Write the golden test vectors (and the generated RTL include files) to ``sim/vectors``.

    PYTHONPATH=python python3 python/scripts/gen_vectors.py
"""

from __future__ import annotations

from _common import ROOT

from btpsd import vectors as V

OUT = ROOT / "sim" / "vectors"


def write_all(OUT=OUT) -> str:
    """Write every golden vector file into ``OUT`` (default ``sim/vectors``); returns the one-line summary."""
    OUT.mkdir(parents=True, exist_ok=True)
    c = V.cru_vectors(16)
    V.write_mem(OUT / "cru_wl16_in.mem", c["in"], c["in_width"])
    V.write_mem(OUT / "cru_wl16_out.mem", c["out"], c["out_width"])
    b = V.bfly_vectors(16)
    V.write_mem(OUT / "bfly_wl16_in.mem", b["in"], b["in_width"])
    V.write_mem(OUT / "bfly_wl16_out.mem", b["out"], b["out_width"])
    f = V.fft_vectors(16)
    for name in ("in_re", "in_im", "out_re", "out_im"):
        V.write_mem(OUT / f"fft_wl16_{name}.mem", f[name], 16)
    (OUT / "fft_wl16.vh").write_text(
        f"// generated by python/scripts/gen_vectors.py\n`define FFT_NCHUNKS {f['nchunks']}\n"
        f"`define FFT_TOTAL_CYCLES {f['total_cycles']}\n`define FFT_STALL_CYCLES {f['stall_cycles']}\n")
    s = V.sq_vectors(16)
    V.write_mem(OUT / "sq_wl16_in.mem", s["in"], s["in_width"])
    V.write_mem(OUT / "sq_wl16_out.mem", s["out"], s["out_width"])
    p = V.psd_vectors(12)
    V.write_mem(OUT / "psd_wl12_x.mem", p["x"], 12)
    V.write_mem(OUT / "psd_wl12_P.mem", p["P"], 2 * 12 + 8)
    (OUT / "psd_wl12.vh").write_text(
        f"// generated by python/scripts/gen_vectors.py\n`define PSD_S {p['S']}\n`define PSD_AVG_SHIFT {p['avg_shift']}\n"
        f"`define PSD_NCHUNKS {p['nchunks']}\n`define PSD_SQUARER_CYCLES {p['squarer_cycles']}\n")
    q = V.bispec_vectors(12)
    bw = 2 * 12 + 10
    V.write_mem(OUT / "bsp_wl12_x.mem", q["x"], 12)
    V.write_mem(OUT / "bsp_wl12_B_re.mem", q["B_re"][: q["cfg"].max_bin, : q["cfg"].max_bin].ravel(), bw)
    V.write_mem(OUT / "bsp_wl12_B_im.mem", q["B_im"][: q["cfg"].max_bin, : q["cfg"].max_bin].ravel(), bw)
    (OUT / "bsp_wl12.vh").write_text(
        f"// generated by python/scripts/gen_vectors.py\n`define BSP_S {q['S']}\n`define BSP_AVG_SHIFT {q['avg_shift']}\n"
        f"`define BSP_MAX_BIN {q['cfg'].max_bin}\n`define BSP_NSAMPLES {len(q['x'])}\n")
    g = V.siggen_vectors(12)
    V.write_mem(OUT / "siggen_wl12_x.mem", g["x"], 12)
    (OUT / "siggen_wl12.vh").write_text(
        f"// generated by python/scripts/gen_vectors.py\n`define SG_N {g['n']}\n`define SG_PINC {g['pinc']}\n"
        f"`define SG_SHIFT_A {g['shift_a']}\n`define SG_SHIFT_C {g['shift_c']}\n")
    t = V.selftest_vectors(12)
    V.write_mem(OUT / "selftest_wl12_P.mem", t["P"], 2 * 12 + 8)
    (OUT / "selftest_wl12.vh").write_text(
        f"// generated by python/scripts/gen_vectors.py\n`define ST_PINC {t['pinc']}\n`define ST_NOISE_SHIFT {t['noise_shift']}\n"
        f"`define ST_NCHUNKS {t['nchunks']}\n")
    (OUT / "README.md").write_text(V.describe())
    return (f"vectors written to {OUT}: cru {c['n']}, bfly {b['n']}, fft {f['nchunks']} chunks, sq {s['n']}, "
            f"psd S={p['S']} shift={p['avg_shift']} squarer cycles={p['squarer_cycles']}, bsp S={q['S']} shift={q['avg_shift']}, "
            f"siggen {g['n']} x 3 (saturated samples in run C: {g['sat_c']}), selftest S={t['S']} shift={t['avg_shift']}")


def main() -> None:
    print(write_all())


if __name__ == "__main__":
    main()
