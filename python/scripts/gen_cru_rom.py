"""Generate the constant-rotator (CRU) coefficient ROM and write it to ``data/cru_rom_*.csv``.

Usage: python python/scripts/gen_cru_rom.py [--tol 0.01] [--out data/cru_rom_generated.csv]
"""
import argparse
import csv

import numpy as np

from _common import DATA
from btpsd.cordic import STEP, generate_rom
from btpsd.fixedpoint import naf


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tol", type=float, default=0.01, help="angle tolerance in rad (paper: 0.01)")
    ap.add_argument("--gain-tol", type=float, default=2.0**-10)
    ap.add_argument("--inv-frac", type=int, default=14)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    rom = generate_rom(tol=a.tol, gain_tol=a.gain_tol, inv_frac=a.inv_frac)
    out = a.out or str(DATA / ("cru_rom_generated.csv" if abs(a.tol - 0.01) < 1e-12 else f"cru_rom_tol{a.tol:g}.csv"))
    ae, ge, w, ad = rom.angle_error(), rom.gain_error(), rom.weights(), rom.adders()
    with open(out, "w", newline="") as f:
        wr = csv.writer(f)
        wr.writerow(["r", "angle_pi_over_512", "a", "b", "inv", "inv_frac", "angle_err_rad", "angle_err_steps",
                     "gain_err", "csd_a", "csd_b", "csd_inv", "w_a", "w_b", "w_inv", "adders_model", "source"])
        for r in range(rom.n):
            fmt = lambda v: " ".join(f"{'+' if s > 0 else '-'}2^{e}" for s, e in naf(int(v)))
            wr.writerow([r, r, rom.a[r], rom.b[r], rom.inv[r], rom.inv_frac, f"{ae[r]:.6f}", f"{ae[r] / STEP:.4f}",
                         f"{ge[r]:.6f}", fmt(rom.a[r]), fmt(rom.b[r]), fmt(rom.inv[r]), *w[r], ad[r],
                         f"generated by btpsd.cordic.generate_rom(tol={a.tol}, gain_tol={a.gain_tol})"])
    print(f"wrote {out}: max|angle err| = {np.abs(ae[1:]).max():.5f} rad, mean adders = {ad[1:].mean():.2f}")


if __name__ == "__main__":
    main()
